"""Bot configuration.

Two sources, deliberately separate:
- bot/config.yaml — the MODEL config, GENERATED by
  `scripts/build_report.py --emit-bot-config`. This file is the eval ->
  deployment link: the bot runs whatever won the benchmark, verbatim.
- Environment variables — Matrix credentials and behavior knobs
  (cooldown, message-length guard, window size). # DECISION: behavior via
  env with safe defaults, so the generated file stays purely the eval output.
"""

from __future__ import annotations

import os
from pathlib import Path

import yaml
from pydantic import BaseModel, Field

DEFAULT_CONFIG_PATH = Path(__file__).resolve().parents[1] / "config.yaml"


class WinnerConfig(BaseModel):
    """Contents of the generated bot/config.yaml."""

    model_key: str
    provider: str
    provider_base_url: str
    api_key_env: str
    model_id: str
    prompt_version: str
    rate_limit_rpm: int = Field(gt=0)
    rate_limit_rpd: int = Field(gt=0)
    max_output_tokens: int = 1024


class BotSettings(BaseModel):
    homeserver: str
    user_id: str
    access_token: str
    default_lang: str = "en"
    feedback_cooldown_s: float = 30.0     # max 1 feedback reply per user per N s
    max_message_chars: int = 1000         # longer messages get no feedback
    level_window_size: int = 10           # rolling per-(room,user) message window
    metrics_port: int = 9100


def load_winner_config(path: Path | None = None) -> WinnerConfig:
    p = path or DEFAULT_CONFIG_PATH
    if not p.exists():
        raise FileNotFoundError(
            f"{p} not found. Generate it from eval results with:\n"
            "  uv run python scripts/build_report.py --emit-bot-config\n"
            "or copy bot/config.yaml.example and fill it in by hand."
        )
    with p.open("r", encoding="utf-8") as f:
        data = yaml.safe_load(f)
    if not isinstance(data, dict):
        raise ValueError(f"{p} must be a YAML mapping")
    return WinnerConfig(**data)


def load_settings() -> BotSettings:
    missing = [
        v for v in ("MATRIX_HOMESERVER", "MATRIX_USER_ID", "MATRIX_ACCESS_TOKEN")
        if not os.environ.get(v, "").strip()
    ]
    if missing:
        raise RuntimeError(
            f"missing required environment variables: {', '.join(missing)} "
            "(see .env.example at the repo root)"
        )
    return BotSettings(
        homeserver=os.environ["MATRIX_HOMESERVER"].strip(),
        user_id=os.environ["MATRIX_USER_ID"].strip(),
        access_token=os.environ["MATRIX_ACCESS_TOKEN"].strip(),
        default_lang=os.environ.get("POLYGLOT_DEFAULT_LANG", "en").strip() or "en",
        feedback_cooldown_s=float(os.environ.get("POLYGLOT_COOLDOWN_S", "30")),
        max_message_chars=int(os.environ.get("POLYGLOT_MAX_MSG_CHARS", "1000")),
        level_window_size=int(os.environ.get("POLYGLOT_WINDOW_SIZE", "10")),
        metrics_port=int(os.environ.get("POLYGLOT_METRICS_PORT", "9100")),
    )
